import java.awt.Font;
import java.awt.font.FontRenderContext;
import java.awt.geom.AffineTransform;
import java.awt.geom.PathIterator;
import java.nio.file.*;

/** Rebuilds the launcher, system splash and themed mark from Albion's bundled Literata. */
class ExportMonogram {
    public static void main(String[] args) throws Exception {
        if (args.length != 2) throw new IllegalArgumentException("Usage: ExportMonogram <literata.ttf> <res/drawable>");
        Font font = Font.createFont(Font.TRUETYPE_FONT, Path.of(args[0]).toFile()).deriveFont(100f);
        var glyph = font.createGlyphVector(new FontRenderContext(null, true, true), "A").getOutline();
        var bounds = glyph.getBounds2D();
        double scale = 38 / bounds.getHeight();
        var transform = new AffineTransform();
        transform.translate(54 - bounds.getCenterX() * scale, 51 - bounds.getCenterY() * scale);
        transform.scale(scale, scale);
        StringBuilder path = new StringBuilder();
        double[] c = new double[6];
        for (var it = glyph.getPathIterator(transform); !it.isDone(); it.next()) {
            int type = it.currentSegment(c);
            String command = new String[]{"M", "L", "Q", "C", "Z"}[type];
            path.append(command);
            int count = new int[]{2, 2, 4, 6, 0}[type];
            for (int i = 0; i < count; i++) path.append(String.format(java.util.Locale.US, "%.3f", c[i])).append(i+1 == count ? " " : ",");
        }
        StringBuilder stem = new StringBuilder();
        StringBuilder leaves = new StringBuilder();
        for (int side : new int[]{-1, 1}) {
            for (int i = 0; i <= 40; i++) {
                double angle = .18 + i * 2.12 / 40;
                stem.append(point(i == 0 ? "M" : "L", side, angle, 25.5));
            }
            for (int i = 0; i < 6; i++) {
                double angle = .38 + i * .32;
                leaves.append(point("M", side, angle, 25.5));
                leaves.append(point("Q", side, angle + .05, 30));
                leaves.append(point("", side, angle + .22, 29));
                leaves.append(point("Q", side, angle + .17, 25.8));
                leaves.append(point("", side, angle, 25.5)).append("Z ");
            }
        }
        String vector = """
            <?xml version="1.0" encoding="utf-8"?>
            <!-- Generated by scripts/ExportMonogram.java from bundled Literata; all ink inside the 66 dp safe zone. -->
            <vector xmlns:android="http://schemas.android.com/apk/res/android"
                android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
                <path android:pathData="%s" android:strokeColor="#D6BD87" android:strokeWidth="0.7" android:strokeLineCap="round" />
                <path android:pathData="%s" android:fillColor="#D6BD87" android:fillAlpha="0.85" />
                <path android:pathData="M54,22.5L55.8,25.2L54,27.9L52.2,25.2Z M54,77L56.2,79.2L54,81.4L51.8,79.2Z" android:fillColor="#D6BD87" />
                <path android:pathData="%s" android:fillColor="#FFF8EB" />
            </vector>
            """.formatted(stem, leaves, path);
        Path output = Path.of(args[1]);
        Files.writeString(output.resolve("ic_launcher_foreground.xml"), vector);
        Files.writeString(output.resolve("splash_mark.xml"), vector);
        Files.writeString(output.resolve("ic_launcher_monochrome.xml"), vector
            .replace("#D6BD87", "#000000").replace("#FFF8EB", "#000000").replace("android:fillAlpha=\"0.85\"", ""));
        System.out.println("Exported Literata monogram, laurel and monochrome mark.");
    }

    private static String point(String command, int side, double angle, double radius) {
        return String.format(java.util.Locale.US, "%s%.3f,%.3f ", command,
            54 + side * Math.sin(angle) * radius, 51 + Math.cos(angle) * radius);
    }
}
